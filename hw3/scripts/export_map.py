#!/usr/bin/env python3
"""Export EKF-SLAM map and trajectory from a running ROS system or recorded data."""

import argparse
from pathlib import Path
import sys

from hw3.data_recorder import export_landmarks_csv, export_trajectory_csv


def main(args=None):
    parser = argparse.ArgumentParser(description="Export trajectory and map to CSV.")
    parser.add_argument('--input-json', '-i', help="Path to recorded JSON run (optional)")
    parser.add_argument('--output-dir', '-o', default='hw3_results', help="Output directory")
    parsed = parser.parse_args(args=args)

    out_dir = Path(parsed.output_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    if parsed.input_json:
        from hw3.data_recorder import DataReplayer
        replayer = DataReplayer(parsed.input_json)
        results = replayer.run()
        traj_csv = out_dir / "exported_trajectory.csv"
        map_csv = out_dir / "exported_landmarks.csv"
        export_trajectory_csv(results['trajectory'], traj_csv)
        export_landmarks_csv(results['landmarks'], map_csv)
        print(f"Exported trajectory ({len(results['trajectory'])} points) to {traj_csv}")
        print(f"Exported map ({len(results['landmarks'])} landmarks) to {map_csv}")
    else:
        print(f"CSVs are automatically generated by ekf_slam_node in {out_dir}/")
        print("To export from recorded file: export_map -i <path_to_json>")


if __name__ == '__main__':
    main()
